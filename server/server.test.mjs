test('dirección, referencias y ubicación opcional confirmada para cada reserva', async t => {
  const saleDate = '2026-11-06';
  const point = { latitude: -12.13, longitude: -76.86, accuracy: 20, capturedAt: 1793290000000, saleDate, address: 'Sector de prueba Mz A Lt 4' };
  const address = point.address;
  assert.equal(deliveryDestination({ address, reference: 'Casa verde', meeting: 'Al pie de la escalera' }, saleDate).reference, 'Casa verde\nAl pie de la escalera');
  assert.ok(deliveryDestination({ address, deliveryLocation: { ...point, latitude: 100 } }, saleDate).error);
  assert.ok(deliveryDestination({ address: 'Otro lugar', deliveryLocation: point }, saleDate).error);
  assert.ok(deliveryDestination({ address, deliveryLocation: point }, '2026-11-13').error);
  const dataDir = mkdtempSync(join(process.cwd(), 'tmp', 'destination-test-'));
  const { server, state } = createApp({ dataDir });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const call = async body => {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api/orders`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ requestId: crypto.randomUUID(), customer: 'Prueba de entrega', phone: '900000000', fulfillment: 'delivery', zoneId: 'cercana', address, reference: 'Casa verde', payment: 'cash', items: [{ productId: 'papa', quantity: 1 }], ...body }) });
    return { status: response.status, data: await response.json() };
  };
  const confirmed = { ...point, saleDate: state.settings.saleDate };
  const placed = await call({ deliveryLocation: confirmed });assert.equal(placed.status, 201);assert.deepEqual(placed.data.order.deliveryLocation, confirmed);
  const stock = state.products[0].stock;
  assert.equal((await call({ address: 'Otra dirección', deliveryLocation: confirmed })).status, 400);assert.equal(state.products[0].stock, stock);
  assert.equal((await call({})).status, 201);
  const pickup = await call({ fulfillment: 'pickup', deliveryLocation: { latitude: 'invalid' } });assert.equal(pickup.status, 201);assert.equal(pickup.data.order.deliveryLocation, undefined);
  confirmed.latitude = 0;assert.equal(state.orders.find(o => o.id === placed.data.order.id).deliveryLocation.latitude, -12.13);
});

test('reservas anticipadas, cierre, fechas conservadas y entrega programada', async t => {
  const dataDir = mkdtempSync(join(process.cwd(), 'tmp', 'schedule-test-'));
  let clock = time('2026-10-19T09:00'); // Monday in Lima.
  const { server, state } = createApp({ dataDir, now: () => clock });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = async (path, body, admin = false) => {
    const response = await fetch(base + path, { method: body ? 'POST' : 'GET', headers: { 'Content-Type': 'application/json', ...(admin ? { 'X-Manchapp-Key': state.adminKey } : {}) }, body: body ? JSON.stringify(body) : undefined });
    return { status: response.status, data: await response.json() };
  };
  const schedule = { saleDate: '2026-10-23', pickupFrom: '2026-10-23T16:00', pickupUntil: '2026-10-23T19:00', reserveUntil: '2026-10-22T20:00', salesOpen: true };
  const settings = value => call('/api/admin/operations', { id: crypto.randomUUID(), type: 'settings', data: { ...state.settings, ...value } }, true);
  assert.equal((await settings(schedule)).status, 200);
  const draft = { customer: 'Reserva anticipada', phone: '900000000', fulfillment: 'pickup', payment: 'cash', items: [{ productId: 'papa', quantity: 1 }] };
  const reserve = (extra = {}) => call('/api/orders', { ...draft, requestId: crypto.randomUUID(), ...extra });
  const pickup = await reserve(); assert.equal(pickup.status, 201); assert.equal(pickup.data.order.saleDate, '2026-10-23');
  const delivery = await reserve({ fulfillment: 'delivery', zoneId: 'cercana', address: 'Pasaje de prueba', reference: 'Junto a la bodega' }); assert.equal(delivery.status, 201);
  const update = (order, status, extra = {}) => call('/api/admin/operations', { id: crypto.randomUUID(), type: 'order', data: { id: order.id, version: state.orders.find(o => o.id === order.id).version, status, ...extra } }, true);
  assert.equal((await update(pickup.data.order, 'sale_day')).status, 409);
  const stock = state.products[0].stock;
  await settings({ salesOpen: false }); assert.equal((await reserve()).status, 409); assert.equal(state.products[0].stock, stock);
  await settings({ salesOpen: true });
  clock = time(schedule.reserveUntil); assert.equal((await reserve()).status, 409); assert.equal(state.products[0].stock, stock);
  assert.equal((await settings({ pickupUntil: '2026-10-23T15:00' })).status, 400);
  assert.ok(Number.isNaN(time('2026-02-30', true)));
  assert.ok(scheduleError({ ...schedule, reserveUntil: '2026-10-23T18:00' }));
  await settings({ saleDate: '2026-10-30', pickupFrom: '2026-10-30T16:00', pickupUntil: '2026-10-31T10:00', reserveUntil: '2026-10-29T20:00' });
  assert.equal(state.orders.find(o => o.id === pickup.data.order.id).saleDate, '2026-10-23');
  clock = time('2026-10-23T15:59');
  assert.equal((await update(pickup.data.order, 'sale_day')).status, 200);
  assert.equal((await update(pickup.data.order, 'pickup_available')).status, 409);
  clock = time('2026-10-23T16:00');
  assert.equal((await update(pickup.data.order, 'pickup_available')).status, 200);
  assert.equal((await update(pickup.data.order, 'delivered')).status, 200);
  assert.equal((await update(delivery.data.order, 'sale_day')).status, 200);
  assert.equal((await update(delivery.data.order, 'pickup_available')).status, 409);
  assert.equal((await update(delivery.data.order, 'delivering', { driver: 'Ana' })).status, 200);
  assert.equal((await update(delivery.data.order, 'delivered')).status, 200);
  assert.equal(state.orders.find(o => o.id === delivery.data.order.id).paid, false);
});

test('pedidos, privacidad, disponibilidad, estados y persistencia', async t => {
  mkdirSync(join(process.cwd(), 'tmp'), { recursive: true });
  const dataDir = mkdtempSync(join(process.cwd(), 'tmp', 'api-test-'));
  const { server, state } = createApp({ dataDir });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = async (path, data, admin = false, headers = {}) => { const response = await fetch(base + path, { method: data ? 'POST' : 'GET', headers: { 'Content-Type': 'application/json', ...(admin ? { 'X-Manchapp-Key': state.adminKey } : {}), ...headers }, body: data ? JSON.stringify(data) : undefined }); return { status: response.status, data: await response.json() }; };
  assert.equal((await call('/api/admin/state')).status, 401);
  const catalog = (await call('/api/catalog')).data;
  assert.equal(catalog.adminKey, undefined);
  const draft = { requestId: 'test-order-0001', customer: 'Prueba local', phone: '900000000', fulfillment: 'pickup', payment: 'cash', items: [{ productId: 'papa', quantity: 2, price: .01 }] };
  const first = await call('/api/orders', draft);
  assert.equal(first.status, 201); assert.equal(first.data.order.total, 13); assert.equal(first.data.order.paid, false); assert.equal(first.data.order.token, undefined);
  const again = await call('/api/orders', draft); assert.equal(again.data.order.id, first.data.order.id); assert.equal(state.products[0].stock, 18);
  assert.equal((await call('/api/orders/' + first.data.order.id)).status, 404);
  assert.equal((await call('/api/orders/' + first.data.order.id, null, false, { 'X-Order-Token': first.data.token })).status, 200);
  assert.equal((await call('/api/orders', { ...draft, requestId: 'social-00001', items: [{ productId: 'social', quantity: 1 }] })).status, 409);
  assert.equal((await call('/api/orders', { ...draft, requestId: 'oversell-00001', items: [{ productId: 'papa', quantity: 99 }] })).status, 409);
  assert.equal((await call('/api/orders', { ...draft, requestId: 'phone-000001', phone: '123' })).status, 400);
  assert.equal((await call('/api/orders', { ...draft, requestId: 'delivery-001', fulfillment: 'delivery', zoneId: 'cercana' })).status, 400);
  const delivery = await call('/api/orders', { ...draft, requestId: 'delivery-002', fulfillment: 'delivery', zoneId: 'cercana', address: 'Pasaje de prueba', reference: 'Frente al punto de prueba' });
  assert.equal(delivery.status, 201); assert.equal(delivery.data.order.total, 16);
  const orderId = first.data.order.id;
  const op = (id, data) => call('/api/admin/operations', { id, type: 'order', data: { id: orderId, ...data } }, true);
  assert.equal((await op('bad-transition', { version: 1, status: 'delivered' })).status, 409);
  assert.equal((await op('confirmed-op', { version: 1, status: 'confirmed' })).status, 200);
  assert.equal((await op('stale-op', { version: 1, status: 'preparing' })).status, 409);
  const cancel = await op('cancel-op', { version: 2, status: 'cancelled' }); assert.equal(cancel.status, 200);
  const stockAfterCancel = state.products[0].stock;
  assert.equal((await op('cancel-op', { version: 2, status: 'cancelled' })).status, 200); assert.equal(state.products[0].stock, stockAfterCancel);
  const oldProduct = catalog.products[0];
  assert.equal((await call('/api/admin/operations', { id: 'stale-product', type: 'product', data: { ...oldProduct, stock: 100 } }, true)).status, 409);
  const actual = state.products[0];
  assert.equal((await call('/api/admin/operations', { id: 'invalid-sale-unit', type: 'product', data: { ...actual, saleUnit: 'inventado' } }, true)).status, 400);
  assert.equal((await call('/api/admin/operations', { id: 'edit-product', type: 'product', data: { ...actual, hours: 'Horario de prueba', saleUnit: 'portion', portion: 'Una porción de prueba' } }, true)).status, 200);
  assert.equal(state.products[0].saleUnit, 'portion'); assert.equal(state.products[0].portion, 'Una porción de prueba');
  const reloaded = createApp({ dataDir }); assert.equal(reloaded.state.orders.length, 2); assert.equal(reloaded.state.products[0].hours, 'Horario de prueba');
});

test('promoción de reparto: monto mínimo, sectores habilitados y precio confirmado por el servicio', async t => {
  const dataDir = mkdtempSync(join(process.cwd(), 'tmp', 'delivery-test-'));
  const { server, state } = createApp({ dataDir });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = async (path, body, admin = false) => {
    const response = await fetch(base + path, { method: body ? 'POST' : 'GET', headers: { 'Content-Type': 'application/json', ...(admin ? { 'X-Manchapp-Key': state.adminKey } : {}) }, body: body ? JSON.stringify(body) : undefined });
    return { status: response.status, data: await response.json() };
  };
  const settings = value => call('/api/admin/operations', { id: crypto.randomUUID(), type: 'settings', data: { ...state.settings, ...value } }, true);
  assert.equal((await settings({ deliveryFreeFrom: 13 })).status, 200);
  const draft = { customer: 'Prueba reparto', phone: '900000000', fulfillment: 'delivery', zoneId: 'cercana', address: 'Pasaje de prueba', reference: 'Frente a la bodega', payment: 'cash' };
  const order = quantity => call('/api/orders', { ...draft, requestId: crypto.randomUUID(), fee: 0, items: [{ productId: 'papa', quantity, price: 0 }] });
  const below = await order(1);
  assert.equal(below.status, 201); assert.equal(below.data.order.fee, 3); assert.equal(below.data.order.total, 9.5); assert.equal(below.data.order.deliveryOffer, false);
  const exact = await order(2);
  assert.equal(exact.data.order.total, 13); assert.equal(exact.data.order.fee, 0); assert.equal(exact.data.order.deliveryOffer, true);
  const unavailable = await call('/api/orders', { ...draft, requestId: crypto.randomUUID(), zoneId: 'intermedia', items: [{ productId: 'papa', quantity: 2 }] });
  assert.equal(unavailable.status, 400);
  assert.equal((await settings({ deliveryFreeFrom: 0 })).status, 200);
  assert.equal((await order(2)).data.order.total, 16);
  assert.equal(exact.data.order.total, 13);
  assert.equal((await settings({ deliveryFreeFrom: -1 })).status, 400);
  assert.equal((await settings({ catalogUrl: 'javascript:alert(1)' })).status, 400);
  assert.equal((await settings({ catalogUrl: 'https://usuario:clave@example.com' })).status, 400);
  assert.equal((await settings({ catalogUrl: 'http://192.168.1.9:4173' })).status, 200);
  assert.equal((await call('/api/catalog')).data.settings.catalogUrl, 'http://192.168.1.9:4173');
});
